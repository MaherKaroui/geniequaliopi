// Sélection déterministe d'une variante (nonce = seed stagiaire + bucket temps 30 min)
export function pickWordComment(mode: "debut" | "fin", qi: number, seed: number): string {
  const bank = mode === "debut" ? WORD_QCM_HUMAN_COMMENTS.debut : WORD_QCM_HUMAN_COMMENTS.fin;
  const variants = bank[qi] || [];
  if (variants.length === 0) return "";
  const bucket = Math.floor(Date.now() / (30 * 60 * 1000));
  const idx = Math.abs((seed * 131 + qi * 17 + bucket * 7)) % variants.length;
  return variants[idx];
}
